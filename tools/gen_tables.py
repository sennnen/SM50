#!/usr/bin/env python3
"""Generate fixed-point lookup tables for the SM50 engine (no FPU on the fx-CG50)."""
import math, sys
out = sys.argv[1] if len(sys.argv) > 1 else "src/engine/tables.c"
L = ["/* Generated by tools/gen_tables.py - do not edit. */", '#include "fixmath.h"', ""]
# sine table: 4096 entries per full circle, Q14
L.append("const s16 gSinTable[4096 + 1024] = {")
vals = [int(round(math.sin(2*math.pi*i/4096)*16384)) for i in range(4096+1024)]
vals = [max(-16384, min(16384, v)) for v in vals]
for i in range(0, len(vals), 16):
    L.append("    " + ", ".join(str(v) for v in vals[i:i+16]) + ",")
L.append("};\n")
# atan table for atan2: 1025 entries, angle units (65536 = full circle) for ratio 0..1
L.append("const u16 gAtanTable[1025] = {")
vals = [int(round(math.atan(i/1024)/(2*math.pi)*65536)) for i in range(1025)]
for i in range(0, len(vals), 16):
    L.append("    " + ", ".join(str(v) for v in vals[i:i+16]) + ",")
L.append("};\n")
# reciprocal table: (1<<30)/q for q in 0..16384 (q=0 -> max)
L.append("const u32 gRecipTable[RECIP_TABLE_SIZE] = {")
vals = [0x7fffffff] + [(1 << 30) // q for q in range(1, 16385)]
for i in range(0, len(vals), 12):
    L.append("    " + ", ".join(str(v) + "u" for v in vals[i:i+12]) + ",")
L.append("};")
open(out, "w").write("\n".join(L) + "\n")
